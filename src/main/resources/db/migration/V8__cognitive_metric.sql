-- 턴 단위 인지지표 (AI → BE Kafka, 계약: docs/kafka-cognitive-metrics.md)
-- 노인 PK가 아닌 가명 subject_id로 쌓는다 (탈퇴 시 신원 연결만 끊고 수치는 연구용 보관 가능)

CREATE TABLE cognitive_metric (
    id                          BIGINT           GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    turn_id                     VARCHAR(36)      NOT NULL,
    subject_id                  UUID             NOT NULL,
    analyzable                  BOOLEAN          NOT NULL,
    morpheme_token_count        INTEGER,
    utterance_count             INTEGER,
    filler_ratio                DOUBLE PRECISION,
    empty_speech_ratio          DOUBLE PRECISION,
    content_info_unit_ratio     DOUBLE PRECISION,
    words_per_utterance         DOUBLE PRECISION,
    subsequent_onset_latency_ms DOUBLE PRECISION,
    silent_pause_ratio          DOUBLE PRECISION,
    jitter                      DOUBLE PRECISION,
    shimmer                     DOUBLE PRECISION,
    cpp                         DOUBLE PRECISION,
    neural                      TEXT,
    emotion                     TEXT,
    analyzed_at                 TIMESTAMP WITH TIME ZONE NOT NULL,
    created_at                  TIMESTAMP,
    updated_at                  TIMESTAMP,
    CONSTRAINT uk_cognitive_metric_turn UNIQUE (turn_id)
);

CREATE INDEX idx_cognitive_metric_subject_analyzed ON cognitive_metric (subject_id, analyzed_at);
