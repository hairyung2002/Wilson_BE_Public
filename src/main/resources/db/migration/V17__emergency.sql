-- 응급 기록 (api-spec 15장, 결정 G1·G2)
-- AI가 노인 발화에서 감지한 응급 신호. 대화 원문은 담지 않고 어느 턴인지만 남긴다.
-- notified: 보호자에게 알렸는지 (10분 안의 같은 종류 재감지는 기록만 하고 FALSE)

CREATE TABLE emergency (
    id              BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    elderly_id      BIGINT      NOT NULL,
    conversation_id BIGINT      NOT NULL,
    turn_id         VARCHAR(36) NOT NULL,
    category        VARCHAR(20) NOT NULL,
    detected_at     TIMESTAMP   NOT NULL,
    notified        BOOLEAN     NOT NULL,
    acknowledged_at TIMESTAMP,
    acknowledged_by BIGINT,
    created_at      TIMESTAMP,
    updated_at      TIMESTAMP,
    CONSTRAINT fk_emergency_elderly FOREIGN KEY (elderly_id) REFERENCES elderly (id),
    CONSTRAINT fk_emergency_acknowledged_by FOREIGN KEY (acknowledged_by) REFERENCES member (id)
);

CREATE INDEX idx_emergency_elderly_detected ON emergency (elderly_id, detected_at);
