-- 동의·철회 기록 (api-spec 5-12, decisions.md B4). 고치지 않고 쌓으며 종류별 최신 기록이 효력을 가진다.
-- 이 마이그레이션 이전에 등록된 노인은 동의 기록이 없으므로, 원문 공유 동의가 없는 것으로 본다.

CREATE TABLE consent (
    id                   BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    elderly_id           BIGINT      NOT NULL,
    consent_type         VARCHAR(30) NOT NULL,
    agreed               BOOLEAN     NOT NULL,
    version              INTEGER     NOT NULL,
    grantor              VARCHAR(10) NOT NULL,
    granted_by_member_id BIGINT      NOT NULL,
    legal_basis          VARCHAR(20) NOT NULL,
    created_at           TIMESTAMP,
    updated_at           TIMESTAMP,
    CONSTRAINT fk_consent_elderly FOREIGN KEY (elderly_id) REFERENCES elderly (id),
    CONSTRAINT fk_consent_member FOREIGN KEY (granted_by_member_id) REFERENCES member (id)
);

CREATE INDEX idx_consent_elderly_type ON consent (elderly_id, consent_type, id);
