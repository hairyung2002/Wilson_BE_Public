CREATE TABLE schedule (
    id            BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    elderly_id    BIGINT      NOT NULL,
    schedule_type VARCHAR(20) NOT NULL,
    label         VARCHAR(30),
    schedule_time TIME        NOT NULL,
    days_of_week  VARCHAR(30) NOT NULL,
    enabled       BOOLEAN     NOT NULL,
    created_by    VARCHAR(10) NOT NULL,
    created_at    TIMESTAMP,
    updated_at    TIMESTAMP,
    CONSTRAINT fk_schedule_elderly FOREIGN KEY (elderly_id) REFERENCES elderly (id)
);

CREATE INDEX idx_schedule_elderly ON schedule (elderly_id);
CREATE INDEX idx_schedule_due ON schedule (schedule_time) WHERE enabled = TRUE;

ALTER TABLE elderly ADD COLUMN proactive_enabled BOOLEAN NOT NULL DEFAULT TRUE;
ALTER TABLE elderly ADD COLUMN quiet_hours_start TIME NOT NULL DEFAULT '22:00';
ALTER TABLE elderly ADD COLUMN quiet_hours_end TIME NOT NULL DEFAULT '07:00';
