-- Wilson 초기 스키마 (PostgreSQL)
-- 노인/보호자 듀얼 케어 · 대화 · 조기발견 스코어 · 알림

CREATE TABLE member (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email       VARCHAR(255) NOT NULL,
    password    VARCHAR(255) NOT NULL,
    name        VARCHAR(255) NOT NULL,
    member_type VARCHAR(20)  NOT NULL,
    created_at  TIMESTAMP,
    updated_at  TIMESTAMP,
    CONSTRAINT uk_member_email UNIQUE (email)
);

CREATE TABLE elderly (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id  BIGINT NOT NULL,
    birth_date DATE,
    care_note  TEXT,
    created_at TIMESTAMP,
    updated_at TIMESTAMP,
    CONSTRAINT uk_elderly_member UNIQUE (member_id),
    CONSTRAINT fk_elderly_member FOREIGN KEY (member_id) REFERENCES member (id)
);

CREATE TABLE caregiver (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id  BIGINT NOT NULL,
    created_at TIMESTAMP,
    updated_at TIMESTAMP,
    CONSTRAINT uk_caregiver_member UNIQUE (member_id),
    CONSTRAINT fk_caregiver_member FOREIGN KEY (member_id) REFERENCES member (id)
);

CREATE TABLE care_relationship (
    id           BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    caregiver_id BIGINT      NOT NULL,
    elderly_id   BIGINT      NOT NULL,
    relation     VARCHAR(30),
    is_primary   BOOLEAN     NOT NULL DEFAULT FALSE,
    created_at   TIMESTAMP,
    updated_at   TIMESTAMP,
    CONSTRAINT uk_care_relationship UNIQUE (caregiver_id, elderly_id),
    CONSTRAINT fk_care_relationship_caregiver FOREIGN KEY (caregiver_id) REFERENCES caregiver (id),
    CONSTRAINT fk_care_relationship_elderly FOREIGN KEY (elderly_id) REFERENCES elderly (id)
);

CREATE INDEX idx_care_relationship_caregiver ON care_relationship (caregiver_id);
CREATE INDEX idx_care_relationship_elderly ON care_relationship (elderly_id);

CREATE TABLE conversation (
    id         BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    elderly_id BIGINT      NOT NULL,
    channel    VARCHAR(20) NOT NULL,
    started_at TIMESTAMP   NOT NULL,
    ended_at   TIMESTAMP,
    created_at TIMESTAMP,
    updated_at TIMESTAMP,
    CONSTRAINT fk_conversation_elderly FOREIGN KEY (elderly_id) REFERENCES elderly (id)
);

CREATE INDEX idx_conversation_elderly ON conversation (elderly_id);

CREATE TABLE message (
    id              BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT      NOT NULL,
    sender          VARCHAR(20) NOT NULL,
    content         TEXT        NOT NULL,
    created_at      TIMESTAMP,
    updated_at      TIMESTAMP,
    CONSTRAINT fk_message_conversation FOREIGN KEY (conversation_id) REFERENCES conversation (id)
);

CREATE INDEX idx_message_conversation ON message (conversation_id);

CREATE TABLE dementia_signal (
    id               BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    elderly_id       BIGINT      NOT NULL,
    conversation_id  BIGINT,
    memory_score     INTEGER     NOT NULL,
    vocabulary_score INTEGER     NOT NULL,
    emotion_score    INTEGER     NOT NULL,
    risk_level       VARCHAR(20) NOT NULL,
    analyzed_at      TIMESTAMP   NOT NULL,
    created_at       TIMESTAMP,
    updated_at       TIMESTAMP,
    CONSTRAINT fk_dementia_signal_elderly FOREIGN KEY (elderly_id) REFERENCES elderly (id),
    CONSTRAINT fk_dementia_signal_conversation FOREIGN KEY (conversation_id) REFERENCES conversation (id)
);

CREATE INDEX idx_dementia_signal_elderly ON dementia_signal (elderly_id);

CREATE TABLE notification (
    id                  BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_member_id BIGINT      NOT NULL,
    type                VARCHAR(30) NOT NULL,
    title               VARCHAR(255) NOT NULL,
    body                TEXT        NOT NULL,
    is_read             BOOLEAN     NOT NULL DEFAULT FALSE,
    sent_at             TIMESTAMP,
    created_at          TIMESTAMP,
    updated_at          TIMESTAMP,
    CONSTRAINT fk_notification_recipient FOREIGN KEY (recipient_member_id) REFERENCES member (id)
);

CREATE INDEX idx_notification_recipient ON notification (recipient_member_id);
