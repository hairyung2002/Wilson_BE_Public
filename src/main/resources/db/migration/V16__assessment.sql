-- 분석 판정 (api-spec 12장, 결정 D1~D5)
-- 인지지표(cognitive_metric)로 노인·지표별 기준값을 만들고 매일 변화를 판정한다.
-- 기존 dementia_signal(기억·어휘·감정 점수)은 이 설계로 대체한다.

DROP TABLE dementia_signal;

CREATE TABLE elder_baseline (
    id           BIGINT           GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    elderly_id   BIGINT           NOT NULL,
    metric       VARCHAR(40)      NOT NULL,
    mean         DOUBLE PRECISION NOT NULL,
    std          DOUBLE PRECISION NOT NULL,
    period_start DATE             NOT NULL,
    period_end   DATE             NOT NULL,
    created_at   TIMESTAMP,
    updated_at   TIMESTAMP,
    CONSTRAINT uk_elder_baseline_elderly_metric UNIQUE (elderly_id, metric),
    CONSTRAINT fk_elder_baseline_elderly FOREIGN KEY (elderly_id) REFERENCES elderly (id)
);

CREATE TABLE daily_assessment (
    id              BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    elderly_id      BIGINT      NOT NULL,
    assessment_date DATE        NOT NULL,
    risk_level      VARCHAR(10) NOT NULL,
    created_at      TIMESTAMP,
    updated_at      TIMESTAMP,
    CONSTRAINT uk_daily_assessment_elderly_date UNIQUE (elderly_id, assessment_date),
    CONSTRAINT fk_daily_assessment_elderly FOREIGN KEY (elderly_id) REFERENCES elderly (id)
);

-- 지표별 z(그날 데이터가 없으면 NULL)와 데이터가 있는 날 기준 연속 벗어남 횟수
CREATE TABLE daily_assessment_metric (
    assessment_id BIGINT           NOT NULL,
    metric        VARCHAR(40)      NOT NULL,
    z_score       DOUBLE PRECISION,
    streak        INTEGER          NOT NULL,
    CONSTRAINT fk_daily_assessment_metric_assessment FOREIGN KEY (assessment_id) REFERENCES daily_assessment (id)
);

CREATE INDEX idx_daily_assessment_metric_assessment ON daily_assessment_metric (assessment_id);
